const originalText = new WeakMap();
const reverseTranslations = new Map();
for (const dictionary of Object.values(translations)) {
  for (const [source, translated] of Object.entries(dictionary)) {
    if (!reverseTranslations.has(translated))
      reverseTranslations.set(translated, source);
  }
}

const getCanonicalSource = (text) => {
  const trimmed = text.trim();
  return reverseTranslations.get(trimmed) || text;
};

const translateTextNodes = (locale) => {
  const dictionary = translations[locale] || {};
  const walker = document.createTreeWalker(
    document.body,
    NodeFilter.SHOW_TEXT,
    {
      acceptNode(node) {
        if (!node.textContent.trim()) return NodeFilter.FILTER_REJECT;
        if (node.parentElement?.closest("script, style"))
          return NodeFilter.FILTER_REJECT;
        return NodeFilter.FILTER_ACCEPT;
      },
    },
  );

  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);

  for (const node of nodes) {
    if (!originalText.has(node)) {
      originalText.set(node, getCanonicalSource(node.textContent));
    }
    const source = originalText.get(node);
    const trimmed = source.trim();
    const translated = dictionary[trimmed];
    node.textContent = translated
      ? source.replace(trimmed, translated)
      : source;
  }
};

const setLocale = (locale) => {
  const normalized = locale === "ms" ? "ms" : "en";
  document.documentElement.lang = normalized === "ms" ? "ms-MY" : "en-MY";
  document.documentElement.dataset.locale = normalized;
  localStorage.setItem("pestflow-locale", normalized);
  window.dispatchEvent(
    new CustomEvent("pestflow:locale", { detail: { locale: normalized } }),
  );
  translateTextNodes(normalized);
  setTheme(document.documentElement.dataset.theme || "light");
  document.querySelectorAll("[data-language-toggle]").forEach((button) => {
    button.textContent = normalized === "ms" ? "EN" : "BM";
    button.setAttribute(
      "aria-label",
      normalized === "ms" ? "Switch to English" : "Tukar ke Bahasa Melayu",
    );
  });
};

const setTheme = (theme) => {
  const normalized = theme === "dark" ? "dark" : "light";
  document.documentElement.dataset.theme = normalized;
  localStorage.setItem("pestflow-theme", normalized);
  const locale = document.documentElement.dataset.locale || "en";
  document.querySelectorAll("[data-theme-toggle]").forEach((button) => {
    const label = button.querySelector("[data-theme-label]") || button;
    label.textContent =
      locale === "ms"
        ? normalized === "dark"
          ? "Cerah"
          : "Gelap"
        : normalized === "dark"
          ? "Light"
          : "Dark";
    button.setAttribute("aria-pressed", String(normalized === "dark"));
    button.classList.remove("is-pulling");
    requestAnimationFrame(() => button.classList.add("is-pulling"));
    setTimeout(() => button.classList.remove("is-pulling"), 360);
    button.setAttribute(
      "aria-label",
      normalized === "dark" ? "Use light theme" : "Use dark theme",
    );
  });
};

const savedTheme = localStorage.getItem("pestflow-theme");
const preferredTheme = matchMedia("(prefers-color-scheme: dark)").matches
  ? "dark"
  : "light";
setTheme(savedTheme || preferredTheme);
setLocale(localStorage.getItem("pestflow-locale") || "en");

